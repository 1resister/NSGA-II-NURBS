        max(abs(line_derivatives.q_ss), [], 'all') <= 1e-9 && ...
        max(abs(line_derivatives.q_sss), [], 'all') <= 1e-8, ...
    'Analytic NURBS arc-length derivatives are incorrect on a straight line.');
end


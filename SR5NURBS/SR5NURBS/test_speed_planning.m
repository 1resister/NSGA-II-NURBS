end
end

function test_unique_chromosome_floor(cfg)
M = 3;
V = cfg.nsga.num_variables;
pop = max(40, cfg.nsga.min_unique_chromosomes + 1);
columns = V + M + 2;
intermediate = zeros(pop + cfg.nsga.min_unique_chromosomes, columns);
base = [cfg.bounds.weights_lb cfg.bounds.time_lb ...
    cfg.bounds.jerk_utilization_lb];
intermediate(:, 1:V) = repmat(base, size(intermediate, 1), 1);
intermediate(1:pop, V + M + 1) = 1;
intermediate(1:pop, V + M + 2) = Inf;
for i = 1:cfg.nsga.min_unique_chromosomes
    row = pop + i;
    variable_id = cfg.nsga.num_weights + 1;
    intermediate(row, variable_id) = min( ...
        base(variable_id) + 0.01 * i, cfg.bounds.time_ub(1));
    intermediate(row, V + M + 1) = 2;
    intermediate(row, V + M + 2) = 1;
end

selected = replace_chromosome(intermediate, M, V, pop, ...
    cfg.nsga.min_unique_chromosomes);
assert(size(unique(selected(:, 1:V), 'rows'), 1) >= ...
    cfg.nsga.min_unique_chromosomes, ...
    'Environmental selection did not preserve the minimum unique chromosomes.');
assert(abs(cfg.nsga.mutation_probability - 0.20) <= eps, ...
    'The configured mutation probability is not 20 percent.');
end

function test_dynamic_dimensions(cfg)
assert(cfg.dynamic_dimensions.enabled, ...
    'Dynamic path dimensions are not enabled.');
assert(cfg.nurbs.num_control_points >= ...
        cfg.dynamic_dimensions.min_control_points && ...
        cfg.nurbs.num_control_points <= ...
        cfg.dynamic_dimensions.max_control_points, ...
    'Dynamic NURBS control-point count is outside its configured bounds.');
assert(cfg.nsga.num_time_nodes >= ...
        cfg.dynamic_dimensions.min_speed_nodes && ...
        cfg.nsga.num_time_nodes <= ...
        cfg.dynamic_dimensions.max_speed_nodes, ...
    'Dynamic speed-node count is outside its configured bounds.');
assert(cfg.nsga.num_variables == cfg.nurbs.num_control_points + ...
        cfg.nsga.num_time_nodes + 1 && ...
        cfg.nsga.num_jerk_utilization_variables == 1, ...
    'Dynamic chromosome dimension is inconsistent.');
assert(numel(cfg.bounds.weights_lb) == cfg.nurbs.num_control_points && ...
        numel(cfg.bounds.time_lb) == cfg.nsga.num_time_nodes && ...
        cfg.bounds.jerk_utilization_lb == 0 && ...
        cfg.bounds.jerk_utilization_ub == double( ...
            cfg.lmsc_jerk_boundary.enabled && ...
            cfg.lmsc_jerk_boundary.evaluate_during_objective) && ...
        numel(cfg.nsga.reference_decision) == cfg.nsga.num_variables && ...
        cfg.nsga.reference_decision(end) == 0, ...
    'Dynamic variable bounds have inconsistent lengths.');
if cfg.nurbs.force_unit_weights
    assert(all(cfg.bounds.weights_lb == 1) && ...
            all(cfg.bounds.weights_ub == 1), ...
        'Unit-weight B-spline bounds are not fixed at one.');
else
    assert(all(cfg.bounds.weights_lb == 0.1) && ...
            all(cfg.bounds.weights_ub == 1.0), ...
        'NURBS weight bounds are not [0.1, 1.0].');
end
assert(isfield(cfg.nurbs, 'base_control_points') && ...
        size(cfg.nurbs.base_control_points, 1) == ...
        cfg.nurbs.num_control_points, ...
    'The dynamically fitted NURBS control points are missing.');
assert(numel(cfg.nurbs.base_knots) == cfg.nurbs.num_control_points + ...
        cfg.nurbs.degree + 1 && all(diff(cfg.nurbs.base_knots) >= 0), ...
    'The dynamically fitted NURBS knot vector is invalid.');
internal_knots = cfg.nurbs.base_knots(cfg.nurbs.degree + 2: ...
    end - cfg.nurbs.degree - 1);
[~, ~, knot_group] = unique(internal_knots);
assert(isempty(knot_group) || max(accumarray(knot_group(:), 1)) <= ...
        cfg.nurbs.corner_knot_multiplicity, ...
    'An internal knot has greater multiplicity than configured.');
probe_u = linspace(0, 1, 101)';
basis = bspline_basis_matrix(probe_u, cfg.nurbs.num_control_points, ...
    cfg.nurbs.degree, cfg.nurbs.base_knots);
assert(max(abs(sum(basis, 2) - 1)) <= 1e-10, ...
    'The B-spline basis does not form a partition of unity.');
assert(isfinite(cfg.dynamic_dimensions.baseline_error) && ...
        (~cfg.dynamic_dimensions.baseline_target_met || ...
        cfg.dynamic_dimensions.baseline_error <= ...
        cfg.constraints.max_contour_error), ...
    'The dynamic baseline-error diagnostic is inconsistent.');
end

function test_dynamic_lmsc_clustering(cfg)
S = (0:20)';
v_limit = 500 * ones(size(S));
kappa = zeros(size(S));
dynamic_indices = [10; 11; 12];
v_limit(dynamic_indices) = [120; 100; 80];
kappa(dynamic_indices) = [0.1; 0.2; 0.3];
lmsc = detect_lmsc_points(S, v_limit, kappa, cfg, dynamic_indices);
kept_dynamic = lmsc.indices(lmsc.is_dynamic);
assert(isequal(kept_dynamic, 12), ...
    'Adjacent dynamically forced LMSC points were not clustered.');
assert(isequal(lmsc.indices([1 end]), [1; numel(S)]), ...
    'Endpoint preservation removed an interior dynamic LMSC.');

[small_spacing, ~, small_floor] = dynamic_lmsc_spacing(100, 99, S, cfg);
[large_spacing, transition_distance, large_floor] = ...
    dynamic_lmsc_spacing(100, 50, S, cfg);
assert(large_spacing > small_spacing && transition_distance > 0, ...
    'Dynamic LMSC spacing does not increase with transition demand.');
expected_large_spacing = cfg.speed.lmsc_merge_distance_factor * max( ...
    cfg.speed.lmsc_transition_distance_factor * transition_distance, ...
    large_floor);
assert(abs(large_spacing - expected_large_spacing) <= ...
        1e-12 * max(1, expected_large_spacing) && ...
        cfg.speed.lmsc_merge_distance_factor > 1, ...
    'The wider dynamic LMSC merge threshold was not applied.');
assert(abs(small_floor - cfg.speed.lmsc_min_sample_intervals) <= eps && ...
        abs(large_floor - small_floor) <= eps, ...
    'Dynamic LMSC sampling floor is inconsistent with the path resolution.');

fine_S = (0:0.1:2)';
[~, ~, fine_floor] = dynamic_lmsc_spacing(100, 100, fine_S, cfg);
assert(fine_floor < small_floor, ...
    'Dynamic LMSC sampling floor does not adapt to path resolution.');
end

function test_xyz_vibration_metric(cfg)
jerk = [3 0 4; -3 4 -4];
metrics = xyz_vibration_metric(jerk, cfg);
expected_axis_rms = sqrt(mean(jerk.^2, 1));
legacy_combined_rms = sqrt(mean(sum(jerk.^2, 2)));
assert(max(abs(metrics.axis_rms - expected_axis_rms)) <= 1e-12, ...
    'The decomposed X/Y/Z vibration RMS values are incorrect.');
assert(abs(metrics.combined_rms - legacy_combined_rms) <= 1e-12, ...
    'Equal XYZ weights no longer reproduce the original vector jerk RMS.');
expected_peak = max(vecnorm(jerk, 2, 2));
expected_objective = legacy_combined_rms + ...
    cfg.objectives.vibration_peak_weight * expected_peak;
assert(abs(metrics.combined_peak - expected_peak) <= 1e-12 && ...
        abs(metrics.objective_value - expected_objective) <= 1e-12, ...
    'The vibration peak term was not included in the objective.');
assert(abs(sum(metrics.contribution_ratio) - 1) <= 1e-12, ...
    'The XYZ vibration contribution ratios do not sum to one.');

weighted_cfg = cfg;
weighted_cfg.objectives.vibration_axis_weights = [1 2 0.5];
weighted = xyz_vibration_metric(jerk, weighted_cfg);
expected_weighted = norm(expected_axis_rms .* [1 2 0.5], 2);
assert(abs(weighted.combined_rms - expected_weighted) <= 1e-12, ...
    'The configured XYZ vibration weights were not applied.');

snap_cfg = cfg;
snap_cfg.resonance.enabled = false;
snap_time = [0; 0.002; 0.004];
snap_jerk = [0 0 0; 700 0 0; 1400 0 0];
snap_metrics = xyz_vibration_metric(snap_jerk, snap_cfg, snap_time);
expected_snap_ratio = 350000 / snap_cfg.limits.xyz_smax(1);
assert(abs(snap_metrics.axis_snap_peak(1) - 350000) <= 1e-9 && ...
        abs(snap_metrics.axis_snap_ratio(1) - expected_snap_ratio) <= 1e-12 && ...
        snap_metrics.snap_feasible, ...
    'The XYZ snap hard-limit ratio is incorrect.');

crackle_time = (0:4)' * 0.002;
crackle_jerk = [(0:4)'.^3, zeros(5, 2)];
crackle_metrics = xyz_vibration_metric( ...
    crackle_jerk, snap_cfg, crackle_time, [], true);
assert(crackle_metrics.axis_crackle_rms(1) > 0 && ...
        crackle_metrics.combined_equivalent_crackle > 0 && ...
        any(abs(crackle_metrics.crackle(:, 1)) > 0), ...
    'The XYZ Crackle smoothness metric was not evaluated.');
end


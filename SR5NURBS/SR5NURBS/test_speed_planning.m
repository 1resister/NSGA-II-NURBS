expected_3 = [zeros(size(u)), zeros(size(u)), 6*ones(size(u))];
expected = cat(3, expected_0, expected_1, expected_2, expected_3);
assert(max(abs(derivatives - expected), [], 'all') <= 1e-11, ...
    'Analytic NURBS parameter derivatives are incorrect.');


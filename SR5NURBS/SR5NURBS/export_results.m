function export_results(result, ~, candidates, selected_id, cfg)
% 导出所选 Pareto 解的轨迹、运动学数据和完整前沿候选表。

if ~exist(cfg.output_dir, 'dir')
    mkdir(cfg.output_dir);
end

solution_dir = fullfile(cfg.output_dir, sprintf('solution_%03d', selected_id));
if ~exist(solution_dir, 'dir')
    mkdir(solution_dir);
end

writetable(array2table(result.smooth_path, 'VariableNames', {'X','Y','Z'}), ...
    fullfile(solution_dir, 'smooth_path.csv'));
writetable(array2table([result.motion.time result.motion.S result.xyz.points], ...
    'VariableNames', {'time','S','X','Y','Z'}), fullfile(solution_dir, 'position.csv'));
writetable(array2table([result.motion.time result.motion.S result.xyz.velocity], ...
    'VariableNames', {'time','S','Vx','Vy','Vz'}), fullfile(solution_dir, 'velocity.csv'));
writetable(array2table([result.motion.time result.motion.S result.xyz.acceleration], ...
    'VariableNames', {'time','S','Ax','Ay','Az'}), fullfile(solution_dir, 'acceleration.csv'));
writetable(array2table([result.motion.time result.motion.S result.xyz.jerk], ...
    'VariableNames', {'time','S','Jx','Jy','Jz'}), fullfile(solution_dir, 'jerk.csv'));
writetable(array2table([result.motion.time result.motion.S, ...
    result.xyz.jerk_geometry, result.xyz.jerk_coupling, ...
    result.xyz.jerk_tangential, result.xyz.jerk], ...
    'VariableNames', {'time','S','Jgx','Jgy','Jgz','Jcplx','Jcply','Jcplz', ...
    'Jtx','Jty','Jtz','Jx','Jy','Jz'}), ...
    fullfile(solution_dir, 'jerk_components.csv'));
writetable(array2table([result.motion.time result.motion.S, ...
    result.xyz.snap], ...
    'VariableNames', {'time','S','Sx','Sy','Sz'}), ...
    fullfile(solution_dir, 'snap.csv'));
if ~isempty(result.vibration_metrics.crackle)
    writetable(array2table([result.motion.time result.motion.S, ...
        result.vibration_metrics.crackle], ...
        'VariableNames', {'time','S','Cx','Cy','Cz'}), ...
        fullfile(solution_dir, 'crackle.csv'));
end
writetable(array2table([result.arc.S result.geom.kappa result.geom.radius], ...
    'VariableNames', {'S','kappa','radius'}), fullfile(solution_dir, 'curvature.csv'));
path_snap = gradient(result.motion.path_jerk, ...
    median(diff(result.motion.time)));
if isfield(result.motion, 'path_snap')
    path_snap = result.motion.path_snap;
end
writetable(array2table([result.motion.time result.motion.S result.motion.path_velocity ...
    result.motion.path_acceleration result.motion.path_jerk path_snap], ...
    'VariableNames', {'time','S','path_velocity','path_acceleration', ...
    'path_jerk','path_snap'}), ...
    fullfile(solution_dir, 'path_motion.csv'));

validation = result.motion.validation;
vibration = result.vibration_metrics;
constraint_table = table(result.raw_objectives.time, result.raw_objectives.error, ...
    result.raw_objectives.vibration, vibration.axis_rms(1), ...
    vibration.axis_rms(2), vibration.axis_rms(3), ...
    vibration.weighted_axis_rms(1), vibration.weighted_axis_rms(2), ...
    vibration.weighted_axis_rms(3), result.constraint.max_contour_error, ...
    result.constraint.violation, result.constraint.penalty, result.constraint.feasible, ...
    result.constraint.dynamic_ratio, result.constraint.dynamic_violation, ...
    result.constraint.dynamic_penalty, result.constraint.path_feasible, ...
    result.constraint.xyz_feasible, ...
    result.constraint.xyz_snap_limit_enabled, result.constraint.xyz_snap_ratio, ...
    result.constraint.xyz_snap_violation, result.constraint.xyz_snap_feasible, ...
    result.constraint.iterations, ...
    result.constraint.global_time_scaling_enabled, ...
    result.constraint.global_time_scaling_iterations, ...
    result.constraint.global_time_scale, ...
    result.constraint.global_time_scale_minimized, ...
    result.constraint.global_time_scale_refinement_iterations, ...
    result.constraint.global_time_scale_lower_bound, ...
    result.constraint.time_smoothing_enabled, ...
    result.constraint.time_smoothing_accepted, ...
    result.constraint.time_smoothing_duration_scale, ...
    result.constraint.time_smoothing_attempted_duration_scale, ...
    result.constraint.time_smoothing_baseline_score, ...
    result.constraint.time_smoothing_final_score, ...
    result.constraint.time_smoothing_improvement, ...
    result.constraint.time_smoothing_reason, ...
    result.constraint.resonance_enabled, ...
    result.constraint.resonance_configured, ...
    result.constraint.resonance_ratio, ...
    result.constraint.resonance_violation, ...
    result.constraint.resonance_penalty, ...
    result.constraint.resonance_feasible, ...
    validation.max_velocity_ratio, validation.max_acceleration_ratio, ...
    validation.max_jerk_ratio, validation.minimum_velocity, ...
    result.xyz.max_velocity_ratio, result.xyz.max_acceleration_ratio, ...
    result.xyz.max_jerk_ratio, result.xyz.max_snap_ratio, ...
    validation.max_join_jump(1), validation.max_join_jump(2), ...
    validation.max_join_jump(3), validation.max_join_jump(4), ...
    'VariableNames', {'raw_time','raw_error','raw_vibration', ...
    'raw_vibration_x','raw_vibration_y','raw_vibration_z', ...
    'weighted_vibration_x','weighted_vibration_y','weighted_vibration_z', ...
    'max_contour_error', ...
    'error_violation','penalty','feasible','dynamic_ratio','dynamic_violation', ...
    'dynamic_penalty','path_feasible','xyz_feasible', ...
    'xyz_snap_limit_enabled','xyz_snap_ratio', ...
    'xyz_snap_violation','xyz_snap_feasible','constraint_iterations', ...
    'global_time_scaling_enabled','global_time_scaling_iterations', ...
    'global_time_scale','global_time_scale_minimized', ...
    'global_time_scale_refinement_iterations', ...
    'global_time_scale_lower_bound','time_smoothing_enabled', ...
    'time_smoothing_accepted','time_smoothing_duration_scale', ...
    'time_smoothing_attempted_duration_scale', ...
    'time_smoothing_baseline_score','time_smoothing_final_score', ...
    'time_smoothing_improvement','time_smoothing_reason', ...
    'resonance_enabled','resonance_configured', ...
    'resonance_ratio','resonance_violation','resonance_penalty', ...
    'resonance_feasible','path_velocity_ratio', ...
    'path_acceleration_ratio','path_jerk_ratio','minimum_path_velocity', ...
    'xyz_velocity_ratio','xyz_acceleration_ratio','xyz_jerk_ratio','xyz_snap_ratio_max', ...
    'max_S_join_jump','max_V_join_jump','max_A_join_jump','max_J_join_jump'});
writetable(constraint_table, fullfile(solution_dir, 'constraint_status.csv'));

axis_name = ["X"; "Y"; "Z"];
is_dominant = axis_name == vibration.dominant_axis;
resonance = vibration.resonance;
is_resonance_dominant = axis_name == resonance.dominant_axis;
vibration_table = table(axis_name, vibration.axis_rms(:), ...
    vibration.axis_weights(:), vibration.weighted_axis_rms(:), ...
    vibration.contribution_ratio(:), vibration.axis_peak(:), ...
    vibration.axis_snap_rms(:), vibration.axis_snap_peak(:), ...
    vibration.axis_snap_limit(:), vibration.axis_snap_ratio(:), ...
    vibration.axis_crackle_rms(:), vibration.axis_crackle_peak(:), ...
    resonance.configured_axes(:), resonance.unresolved_mode_count(:), ...
    resonance.axis_resonant_jerk_rms(:), ...
    resonance.axis_response_rms(:), resonance.response_rms_limits(:), ...
    resonance.response_ratio(:), is_dominant, is_resonance_dominant, ...
    repmat(vibration.combined_rms, 3, 1), ...
    repmat(vibration.combined_peak, 3, 1), ...
    repmat(vibration.peak_weight, 3, 1), ...
    repmat(vibration.combined_equivalent_snap, 3, 1), ...
    repmat(vibration.snap_weight, 3, 1), ...
    repmat(vibration.combined_equivalent_crackle, 3, 1), ...
    repmat(vibration.crackle_weight, 3, 1), ...
    repmat(resonance.objective_value, 3, 1), ...
    repmat(vibration.objective_value, 3, 1), ...
    'VariableNames', {'axis','jerk_rms','axis_weight','weighted_jerk_rms', ...
    'squared_contribution_ratio','peak_abs_jerk','snap_rms','peak_abs_snap', ...
    'snap_limit','snap_ratio','crackle_rms','peak_abs_crackle', ...
    'resonance_axis_configured','unresolved_mode_count', ...
    'resonant_jerk_rms','predicted_response_rms','response_rms_limit', ...
    'response_ratio','is_dominant','is_resonance_dominant', ...
    'combined_rms','combined_peak', ...
    'peak_weight','combined_equivalent_snap','snap_weight', ...
    'combined_equivalent_crackle','crackle_weight', ...
    'resonance_objective','vibration_objective'});
writetable(vibration_table, fullfile(solution_dir, 'vibration_metrics.csv'));

if ~isempty(resonance.frequency_hz)
    spectrum_table = array2table([resonance.frequency_hz, ...
        resonance.acceleration_power, resonance.jerk_power, ...
        resonance.spectral_weight, resonance.weighted_jerk_power, ...
        resonance.response_power], ...
        'VariableNames', {'frequency_hz', ...
        'acceleration_power_x','acceleration_power_y','acceleration_power_z', ...
        'jerk_power_x','jerk_power_y','jerk_power_z', ...
        'resonance_weight_x','resonance_weight_y','resonance_weight_z', ...
        'weighted_jerk_power_x','weighted_jerk_power_y','weighted_jerk_power_z', ...
        'response_power_x','response_power_y','response_power_z'});
    writetable(spectrum_table, fullfile(solution_dir, 'resonance_spectrum.csv'));
end

speed_table = table(result.constraints.S, result.constraints.v_command, ...
    result.constraints.v_curvature, result.constraints.v_chord, ...
    result.constraints.v_axis, result.constraints.v_geometric_jerk, ...
    result.constraints.v_process, ...
    result.constraints.v_candidate, result.constraints.v_limit, ...
    result.constraints.v_planning_limit, ...
    result.constraints.v_planned, result.constraints.active_constraint, ...
    'VariableNames', {'S','v_command','v_curvature','v_chord','v_axis', ...
    'v_geometric_jerk','v_process','v_candidate','v_limit', ...
    'v_planning_limit','v_planned', ...
    'active_constraint'});
writetable(speed_table, fullfile(solution_dir, 'speed_constraints.csv'));

lmsc_id = (1:numel(result.lmsc.indices))';
lmsc_jerk = zeros(size(lmsc_id));
if isfield(result.motion, 'lmsc_jerk') && ...
        numel(result.motion.lmsc_jerk) == numel(lmsc_id)
    lmsc_jerk = result.motion.lmsc_jerk(:);
end
lmsc_table = table(lmsc_id, result.lmsc.indices, result.lmsc.S, ...
    result.lmsc.velocity, result.lmsc.curvature, lmsc_jerk, ...
    'VariableNames', {'lmsc_id','index','S','velocity_limit','curvature', ...
    'shared_path_jerk'});
writetable(lmsc_table, fullfile(solution_dir, 'lmsc_points.csv'));

spu_start_jerk = zeros(numel(result.spus), 1);
spu_peak_jerk = zeros(numel(result.spus), 1);
spu_end_jerk = zeros(numel(result.spus), 1);
if ~isempty(result.spus) && isfield(result.spus, 'start_jerk')
    spu_start_jerk = [result.spus.start_jerk]';
    if isfield(result.spus, 'peak_jerk')
        spu_peak_jerk = [result.spus.peak_jerk]';
    end
    spu_end_jerk = [result.spus.end_jerk]';
end
spu_table = table([result.spus.id]', [result.spus.start_s]', ...
    [result.spus.end_s]', [result.spus.length]', ...
    [result.spus.start_speed_limit]', [result.spus.end_speed_limit]', ...
    [result.spus.candidate_peak_speed]', [result.spus.planned_peak_speed]', ...
    [result.spus.acceleration_time]', [result.spus.constant_time]', ...
    [result.spus.deceleration_time]', spu_start_jerk, spu_peak_jerk, ...
    spu_end_jerk, ...
    'VariableNames', {'spu_id','start_S','end_S','length', ...
    'start_velocity','end_velocity','candidate_peak_velocity', ...
    'planned_peak_velocity','acceleration_time','constant_time', ...
    'deceleration_time','start_shared_jerk','peak_shared_jerk', ...
    'end_shared_jerk'});
writetable(spu_table, fullfile(solution_dir, 'spu_info.csv'));

jerk_report = lmsc_jerk_report(result, cfg);
jerk_summary = table(jerk_report.enabled, ...
    jerk_report.evaluated_during_objective, ...
    jerk_report.decision_variable_feasible, jerk_report.applied, ...
    string(jerk_report.reason), jerk_report.internal_lmsc_count, ...
    sum(jerk_report.active_internal_lmsc), ...
    sum(jerk_report.active_spu_peak), ...
    jerk_report.evaluations, jerk_report.rejected_evaluations, ...
    jerk_report.selected_utilization, jerk_report.baseline_time, ...
    jerk_report.refined_time, jerk_report.time_gain, ...
    jerk_report.time_gain_ratio, jerk_report.baseline_vibration, ...
    jerk_report.refined_vibration, jerk_report.vibration_change_ratio, ...
    jerk_report.baseline_global_time_scale, ...
    jerk_report.refined_global_time_scale, ...
    'VariableNames', {'enabled','evaluated_during_objective', ...
    'decision_variable_feasible','applied','reason','internal_lmsc_count', ...
    'active_internal_lmsc_count','active_spu_peak_count', ...
    'evaluations','rejected_evaluations','selected_utilization', ...
    'baseline_time','refined_time','time_gain','time_gain_ratio', ...
    'baseline_vibration','refined_vibration','vibration_change_ratio', ...
    'baseline_global_time_scale','refined_global_time_scale'});
writetable(jerk_summary, ...
    fullfile(solution_dir, 'lmsc_jerk_boundary_search.csv'));
writetable(jerk_report.trials, ...
    fullfile(solution_dir, 'lmsc_jerk_boundary_candidates.csv'));

local_maximum = nan(numel(lmsc_id), 1);
active_internal = false(numel(lmsc_id), 1);
if numel(lmsc_id) > 2 && ...
        numel(jerk_report.local_maximum_jerk) == numel(lmsc_id) - 2
    local_maximum(2:end-1) = jerk_report.local_maximum_jerk(:);
    active_internal(2:end-1) = jerk_report.active_internal_lmsc(:);
end
requested_jerk = zeros(numel(lmsc_id), 1);
if numel(jerk_report.requested_unscaled_lmsc_jerk) == numel(lmsc_id)
    requested_jerk = jerk_report.requested_unscaled_lmsc_jerk(:);
end
jerk_values = table(lmsc_id, result.lmsc.S, active_internal, ...
    local_maximum, requested_jerk, lmsc_jerk, ...
    'VariableNames', {'lmsc_id','S','active_internal_lmsc', ...
    'local_maximum_unscaled_jerk','requested_unscaled_jerk', ...
    'applied_scaled_jerk'});
writetable(jerk_values, ...
    fullfile(solution_dir, 'lmsc_jerk_boundary_values.csv'));

spu_id = (1:numel(result.spus))';
requested_peak_jerk = zeros(numel(spu_id), 1);
if numel(jerk_report.requested_unscaled_spu_peak_jerk) == numel(spu_id)
    requested_peak_jerk = ...
        jerk_report.requested_unscaled_spu_peak_jerk(:);
end
applied_peak_jerk = zeros(numel(spu_id), 1);
if isfield(result.motion, 'spu_peak_jerk') && ...
        numel(result.motion.spu_peak_jerk) == numel(spu_id)
    applied_peak_jerk = result.motion.spu_peak_jerk(:);
end
spu_peak_values = table(spu_id, jerk_report.spu_peak_S(:), ...
    jerk_report.applied_spu_peak_S(:), ...
    jerk_report.active_spu_peak(:), ...
    jerk_report.local_maximum_peak_jerk(:), requested_peak_jerk, ...
    applied_peak_jerk, ...
    'VariableNames', {'spu_id','baseline_peak_S','applied_peak_S', ...
    'active_nonconstant_peak', ...
    'local_maximum_jerk_magnitude','requested_unscaled_peak_jerk', ...
    'applied_scaled_peak_jerk'});
writetable(spu_peak_values, ...
    fullfile(solution_dir, 'spu_peak_jerk_boundary_values.csv'));

pareto = candidates(:, 2:4);
writetable(array2table(pareto, 'VariableNames', {'Time','Error','Vibration'}), ...
    fullfile(cfg.output_dir, 'pareto_front.csv'));

selected_row = candidates(candidates(:, 1) == selected_id, :);
selected_names = candidate_variable_names(cfg);
writetable(array2table(selected_row, 'VariableNames', selected_names), ...
    fullfile(solution_dir, 'selected_solution.csv'));
exported_objectives = table(selected_id, selected_row(2), selected_row(3), ...
    selected_row(4), result.raw_objectives.time, ...
    result.raw_objectives.error, result.raw_objectives.vibration, ...
    jerk_report.applied, jerk_report.selected_utilization, ...
    'VariableNames', {'solution_id','pareto_objective_time', ...
    'pareto_objective_error','pareto_objective_vibration','reevaluated_time', ...
    'reevaluated_error','reevaluated_vibration','shared_jerk_applied', ...
    'selected_jerk_utilization'});
writetable(exported_objectives, ...
    fullfile(solution_dir, 'exported_solution_objectives.csv'));
end

function report = lmsc_jerk_report(result, cfg)
if isfield(result, 'lmsc_jerk_boundary_search')
    report = result.lmsc_jerk_boundary_search;
    if ~isfield(report, 'evaluated_during_objective')
        report.evaluated_during_objective = false;
    end
    if ~isfield(report, 'decision_variable_feasible')
        report.decision_variable_feasible = true;
    end
    return
end
internal_count = max(numel(result.lmsc.indices) - 2, 0);
report.enabled = logical(cfg.lmsc_jerk_boundary.enabled);
report.evaluated_during_objective = false;
report.decision_variable_feasible = true;
report.applied = false;
report.reason = "not_requested";
report.internal_lmsc_count = internal_count;
report.evaluations = 0;
report.rejected_evaluations = 0;
report.selected_utilization = 0;
report.baseline_time = result.raw_objectives.time;
report.refined_time = result.raw_objectives.time;
report.time_gain = 0;
report.time_gain_ratio = 0;
report.baseline_vibration = result.raw_objectives.vibration;
report.refined_vibration = result.raw_objectives.vibration;
report.vibration_change_ratio = 0;
report.baseline_global_time_scale = result.constraint.global_time_scale;
report.refined_global_time_scale = result.constraint.global_time_scale;
report.local_maximum_jerk = zeros(internal_count, 1);
report.active_internal_lmsc = false(internal_count, 1);
spu_count = numel(result.spus);
report.local_maximum_peak_jerk = zeros(spu_count, 1);
report.active_spu_peak = false(spu_count, 1);
report.spu_peak_S = nan(spu_count, 1);
report.applied_spu_peak_S = nan(spu_count, 1);
report.requested_unscaled_lmsc_jerk = zeros(internal_count + 2, 1);
report.applied_scaled_lmsc_jerk = zeros(internal_count + 2, 1);
report.requested_unscaled_spu_peak_jerk = zeros(spu_count, 1);
report.applied_scaled_spu_peak_jerk = zeros(spu_count, 1);
report.trials = table(0, result.constraint.feasible, ...
    result.constraint.feasible, result.raw_objectives.time, ...
    result.raw_objectives.vibration, result.constraint.global_time_scale, ...
    "zero_jerk_baseline", ...
    'VariableNames', {'utilization','feasible','acceptable','final_time', ...
    'vibration','global_time_scale','reason'});
end

function names = candidate_variable_names(cfg)
names = cell(1, 6 + cfg.nsga.num_weights + cfg.nsga.num_time_nodes);
names(1:5) = {'solution_id','Time','Error','Vibration','chromosome_row'};
for i = 1:cfg.nsga.num_weights
    names{5 + i} = sprintf('weight_%d', i);
end
for i = 1:cfg.nsga.num_time_nodes
    names{5 + cfg.nsga.num_weights + i} = sprintf('time_node_%d', i);
end
names{end} = 'endpoint_jerk_utilization';
end
